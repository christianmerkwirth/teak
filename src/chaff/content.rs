//! Content checks: templates, generated markers, and minified code (FR-38
//! to FR-42). They run on the head that `io::read_head` gives with
//! [`READ_MAX`], once per checked file, and only for text files that type
//! detection read.

use super::ChaffClass;
use super::templates::{Templates, fnv1a64, normalize};

/// The most that one check read takes (FR-42). The GPL-3.0 text is about
/// 35 KiB, so templates fit.
pub const READ_MAX: usize = 64 * 1024;

/// Markers count only in this many first bytes (FR-38).
const MARKER_SPAN: usize = 2048;

/// Case-sensitive generated-code markers.
const MARKERS: &[&[u8]] = &[
    b"DO NOT EDIT",
    b"@generated",
    b"Code generated by",
    b"autogenerated",
    b"auto-generated",
    b"This file was automatically generated",
];

/// The smallest minified file, and the span with no line break that marks
/// one.
const MINIFIED_MIN: u64 = 4096;

/// A head whose lines are longer than this on average is minified.
const MINIFIED_LINE: usize = 500;

/// The class of a text file from its head, and the template id for a
/// template match (0 for none). `size` is the file size; a template can
/// match only when the head holds the whole file.
pub fn check(head: &[u8], size: u64, templates: &Templates) -> Option<(ChaffClass, u16)> {
    if let Some(found) = template(head, size, templates) {
        return Some(found);
    }
    let early = &head[..head.len().min(MARKER_SPAN)];
    if MARKERS.iter().any(|m| contains(early, m)) {
        return Some((ChaffClass::Generated, 0));
    }
    if size >= MINIFIED_MIN && minified(head) {
        return Some((ChaffClass::Minified, 0));
    }
    None
}

/// The class and id of the template that matches the whole file.
pub fn template(head: &[u8], size: u64, templates: &Templates) -> Option<(ChaffClass, u16)> {
    if size > READ_MAX as u64 || head.len() as u64 != size {
        return None;
    }
    let (id, class) = templates.find(fnv1a64(&normalize(head)))?;
    Some((class, id))
}

/// No line break in the first 4 KiB, or long lines on average.
fn minified(head: &[u8]) -> bool {
    let first = &head[..head.len().min(MINIFIED_MIN as usize)];
    if !first.contains(&b'\n') {
        return true;
    }
    let breaks = head.iter().filter(|&&b| b == b'\n').count();
    let lines = breaks + usize::from(head.last() != Some(&b'\n'));
    head.len() / lines.max(1) > MINIFIED_LINE
}

fn contains(hay: &[u8], needle: &[u8]) -> bool {
    hay.windows(needle.len()).any(|w| w == needle)
}

//! Content chaff checks: generated markers (FR-38), minified files (FR-39),
//! and the read bounds of the checks (FR-42).

mod support;

use teak::chaff::ChaffClass;

use support::{Fixture, node, run, scan, strip_glyphs};

fn class(s: &teak::Scan, rel: &str) -> Option<ChaffClass> {
    s.tags[node(s, rel) as usize].class
}

/// The chaff line of the root, as text.
fn chaff_line(out: &support::Run) -> String {
    out.lines()
        .into_iter()
        .find(|l| support::depth(l) == 1 && strip_glyphs(l).starts_with("▪ chaff"))
        .unwrap_or_else(|| panic!("no chaff line in:\n{}", out.stdout))
        .to_string()
}

const MARKER: &str = "// Code generated by protoc-gen-go. DO NOT EDIT.\n";

fn generated_fixture() -> Fixture {
    let fx = Fixture::new();
    let mut late = String::from("package api\n\n");
    while late.len() < 3000 {
        late.push_str("// A comment line that pads the file to 3,000 bytes.\n");
    }
    late.push_str(MARKER);
    fx.file(
        "a.go",
        format!("{MARKER}\npackage api\n\nfunc A() int {{ return 1 }}\n"),
    )
    .file("b.go", late)
    .file("main.go", "package main\n\nfunc main() {}\n");
    fx
}

// FR-38: Generated markers

#[test]
fn fr38_a_marker_in_the_first_2_kib_means_generated() {
    let fx = generated_fixture();
    let s = scan(fx.path(), &[]);
    assert_eq!(class(&s, "a.go"), Some(ChaffClass::Generated));
    assert_eq!(class(&s, "b.go"), None, "the marker is at byte 3,000");
    assert_eq!(class(&s, "main.go"), None);
    let out = run(&fx, &[]);
    assert!(out.row("a.go").is_none(), "{}", out.stdout);
    assert!(chaff_line(&out).contains("a.go"), "{}", out.stdout);
    out.must_row("b.go");
    assert!(out.footer().contains("generated 1"), "{}", out.footer());
}

#[test]
fn fr38_detect_off_finds_no_markers() {
    let fx = generated_fixture();
    let s = scan(fx.path(), &["--detect", "off"]);
    assert_eq!(class(&s, "a.go"), None);
}

#[test]
fn fr38_every_marker_counts_and_case_matters() {
    let fx = Fixture::new();
    let markers = [
        "DO NOT EDIT",
        "@generated",
        "Code generated by",
        "autogenerated",
        "auto-generated",
        "This file was automatically generated",
    ];
    // Names with no digits, so the files do not form a series (FR-44).
    for (i, m) in markers.iter().enumerate() {
        fx.file(
            &format!("{}.txt", support::word(i)),
            format!("header\n{m}\nbody\n"),
        );
    }
    fx.file("lower.txt", "header\ndo not edit\nbody\n");
    let s = scan(fx.path(), &[]);
    for i in 0..markers.len() {
        let rel = format!("{}.txt", support::word(i));
        assert_eq!(class(&s, &rel), Some(ChaffClass::Generated), "{rel}");
    }
    assert_eq!(class(&s, "lower.txt"), None);
}

#[test]
fn fr38_show_generated_keeps_the_row() {
    let fx = generated_fixture();
    let out = run(&fx, &["--show=generated"]);
    out.must_row("a.go");
}

// FR-39: Minified files

#[test]
fn fr39_long_lines_mean_minified() {
    let fx = Fixture::new();
    let one_line = "var a=1;".repeat(25_000);
    let mut lines = String::new();
    while lines.len() < 200_000 {
        lines.push_str(&format!(
            "{:<79}\n",
            "var a = 1; // a line of 80 characters"
        ));
    }
    fx.file("app.js", one_line)
        .file("lib.js", lines)
        .file("x.min.js", "var a=1;\n")
        .file("short.js", "var a=1;".repeat(300))
        .file("main.rs", "fn main() {}\n");
    let s = scan(fx.path(), &[]);
    assert_eq!(class(&s, "app.js"), Some(ChaffClass::Minified));
    assert_eq!(class(&s, "lib.js"), None);
    assert_eq!(
        class(&s, "x.min.js"),
        Some(ChaffClass::Minified),
        "name rule"
    );
    assert_eq!(class(&s, "short.js"), None, "below 4 KiB");
}

// FR-42: Bounded reads for content checks

#[cfg(feature = "test-hooks")]
fn reads_fixture() -> Fixture {
    let fx = generated_fixture();
    let mut big = String::new();
    while big.len() < 1 << 20 {
        big.push_str("a line of plain text in a large file\n");
    }
    fx.file("big.txt", big)
        .file("app.js", "var a=1;".repeat(25_000))
        .file("LICENSE", support::mit_license(2026, "Jane Doe"))
        .file("logo.png", support::corpus("logo.png"));
    for i in 0..40 {
        fx.file(&format!("data/part{i:02}.csv"), "a,b\n1,2\n");
    }
    fx
}

#[cfg(feature = "test-hooks")]
#[test]
fn fr42_checks_read_at_most_64_kib_more_and_no_new_files() {
    let fx = reads_fixture();
    let args = ["--detect", "full", "-n", "12"];
    let (on_run, on) = support::run_report(fx.path(), &args);
    let (_, off) =
        support::run_report_env(fx.path(), &args, &[("TEAK_TEST_NO_CONTENT_CHECKS", "1")]);
    assert_eq!(on_run.code, Some(0), "{on_run:?}");
    assert!(!on.reads.is_empty());
    for (path, bytes) in &on.reads {
        let Some(base) = off.reads.get(path) else {
            panic!("{path} is read only with the checks on: {on:?} / {off:?}");
        };
        assert!(*bytes <= base + 65_536, "{path}: {bytes} > {base} + 65536");
    }
}

#[cfg(feature = "test-hooks")]
#[test]
fn fr42_a_large_text_file_gets_one_64_kib_check_read() {
    let fx = reads_fixture();
    let (_, on) = support::run_report(fx.path(), &["--detect", "full"]);
    let (_, off) = support::run_report_env(
        fx.path(),
        &["--detect", "full"],
        &[("TEAK_TEST_NO_CONTENT_CHECKS", "1")],
    );
    let (on, off) = (on.reads["./big.txt"], off.reads["./big.txt"]);
    assert_eq!(on - off, 65_536, "on {on}, off {off}");
}
